package com.watersupply.tracker.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * A water supply complaint registered by a resident. Table: complaints.
 *
 * Two identifiers:
 *  - id            : internal auto-increment number (1, 2, 3 ...) generated by MySQL.
 *  - complaintCode : public ID shown to residents, e.g. "WSC-2026-1013",
 *                    built from the id after the first save (see ComplaintIdGenerator).
 */
@Entity
@Table(name = "complaints", indexes = {
        @Index(name = "idx_complaints_status", columnList = "status"),
        @Index(name = "idx_complaints_area", columnList = "area")
})
public class Complaint {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "complaint_code", unique = true, length = 20)
    private String complaintCode;

    @Column(name = "resident_name", nullable = false, length = 100)
    private String residentName;

    @Column(nullable = false, length = 10)
    private String phone;

    @Column(length = 150)
    private String email;

    @Column(nullable = false, length = 100)
    private String area;

    @Column(nullable = false, length = 255)
    private String address;

    /** EnumType.STRING stores "PIPELINE_LEAKAGE" instead of a number - readable and safe to reorder. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private ComplaintType type;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Priority priority;

    @Column(nullable = false, length = 1000)
    private String description;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private ComplaintStatus status;

    /** Null until the control room assigns a team. LAZY = only loaded from the DB when needed. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assigned_team_id")
    private MaintenanceTeam assignedTeam;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /**
     * Timeline entries. cascade = ALL means saving the complaint also saves new history rows;
     * orphanRemoval deletes history rows if a complaint is deleted.
     */
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("changedAt ASC, id ASC")
    private List<StatusHistory> history = new ArrayList<>();

    protected Complaint() {
        // required by JPA
    }

    public Complaint(String residentName, String phone, String email, String area, String address,
                     ComplaintType type, Priority priority, String description, Instant createdAt) {
        this.residentName = residentName;
        this.phone = phone;
        this.email = email;
        this.area = area;
        this.address = address;
        this.type = type;
        this.priority = priority;
        this.description = description;
        this.status = ComplaintStatus.SUBMITTED;
        this.createdAt = createdAt;
        this.updatedAt = createdAt;
    }

    /** Adds a timeline entry and keeps both sides of the relationship in sync. */
    public void addHistory(StatusHistory entry) {
        entry.setComplaint(this);
        history.add(entry);
    }

    public Long getId() {
        return id;
    }

    public String getComplaintCode() {
        return complaintCode;
    }

    public void setComplaintCode(String complaintCode) {
        this.complaintCode = complaintCode;
    }

    public String getResidentName() {
        return residentName;
    }

    public String getPhone() {
        return phone;
    }

    public String getEmail() {
        return email;
    }

    public String getArea() {
        return area;
    }

    public String getAddress() {
        return address;
    }

    public ComplaintType getType() {
        return type;
    }

    public Priority getPriority() {
        return priority;
    }

    public String getDescription() {
        return description;
    }

    public ComplaintStatus getStatus() {
        return status;
    }

    public void setStatus(ComplaintStatus status) {
        this.status = status;
    }

    public MaintenanceTeam getAssignedTeam() {
        return assignedTeam;
    }

    public void setAssignedTeam(MaintenanceTeam assignedTeam) {
        this.assignedTeam = assignedTeam;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }

    public List<StatusHistory> getHistory() {
        return history;
    }
}
